"""Copy the pipeline-free parts of the URP theatre's HLSL into the HDRP fork, unchanged.

    python -I port_hlsl.py

The HDRP spike (D202) keeps the theatre's own code for everything that is not lighting: the cell
mottle, the carve, the pinch at a joint, and the shape of a body (its carve, taper, bend and leaf).
Those are copied here from unity/Assets/Theatre, cut at named markers rather than line numbers, so
running this again after unity/'s theatre changes brings the change across. What is cut out is
the lighting, the fog and the caustics, which HDRP does itself in the spike.

The light shafts and the marine snow are the exception. HDRP's volumetric fog drew no shaft under
forty metres of water, and HDRP has nothing like the snow's shells, so the spike draws both with the
URP theatre's own code, as passes over the frame (TheatreWaterPass.shader). Their helpers are copied
here too: the wave field, the caustic gain, the sun under the water, the clip to the water's box,
the shaft march's sheets and caps, the run's snow field and the shells' grid walk.

Writes unity-hdrp/Assets/Theatre/Hdrp/TheatreNoiseHdrp.hlsl, TheatreBodyShape.hlsl,
TheatreLightFieldHdrp.hlsl, TheatreShaftHdrp.hlsl and TheatreSnowHdrp.hlsl.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "unity", "Assets", "Theatre")
DST = os.path.join(ROOT, "unity-hdrp", "Assets", "Theatre", "Hdrp")

BANNER = ("// Generated by unity-hdrp/tools/port_hlsl.py from unity/Assets/Theatre/{src}. Do not edit:\n"
          "// change the source and run the tool again. The HDRP spike (D202) keeps the theatre's own code\n"
          "// for everything that is not lighting, and for the light shafts.\n\n")


def function(text, signature):
    """One function, from its signature to its closing brace, with the comment block above it."""
    m = re.search(re.escape(signature), text)
    if not m:
        raise SystemExit(f"not found: {signature}")
    start = text.rfind("\n\n", 0, m.start()) + 2
    depth, i = 0, text.index("{", m.end())
    for j in range(i, len(text)):
        depth += {"{": 1, "}": -1}.get(text[j], 0)
        if depth == 0:
            return text[start:j + 1] + "\n\n"
    raise SystemExit(f"unbalanced: {signature}")


def between(text, start_marker, end_marker):
    a = text.index(start_marker)
    a = text.rfind("\n\n", 0, a) + 2
    b = text.index(end_marker, a)
    b = text.rfind("\n\n", 0, b) + 1
    return text[a:b]


def write(name, src, body, guard):
    os.makedirs(DST, exist_ok=True)
    path = os.path.join(DST, name)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"#ifndef {guard}\n#define {guard}\n\n" + BANNER.format(src=src) + body + f"#endif\n")
    print("wrote", path)


def main():
    water = open(os.path.join(SRC, "TheatreWater.hlsl"), encoding="utf-8").read()
    noise = "".join(function(water, s) for s in (
        "float3 EvoHash3(float3 p)",
        "float EvoHash1(float2 p)",
        "void EvoVoronoi(float3 p,",
        "float EvoHash1(float3 p)",
        "float EvoValueNoise(float3 p,",
        "float3 EvoCarveOffset(float seed)",
        "float EvoCarveDetail(float smallestHalfMetres)",
        "float EvoCarve(float3 p,",
        "float EvoPinch(float3 p,"))
    write("TheatreNoiseHdrp.hlsl", "TheatreWater.hlsl", noise, "EVOSIM_THEATRE_NOISE_HDRP_INCLUDED")

    # The light the surface sends down, for the shafts: the globals and dials from the wave field
    # to the waterline, the look's switches, and the functions the march calls. None of it reads
    # the camera, which HDRP's camera-relative rendering puts at the origin.
    volume = open(os.path.join(SRC, "TheatreVolume.hlsl"), encoding="utf-8").read()
    field = between(water, "float4 _EvoRipple;", "// How far through the water a look reaches")
    field += between(water, "bool EvoLookWater()", "// Henyey-Greenstein")
    field += "".join(function(water, s) for s in (
        "float EvoPhaseHG(float cosTheta,",
        "float EvoPhaseTerm(float3 viewDir)",
        "float EvoRipple(float2 xz,",
        "float EvoCausticGain(float3 positionWS,",
        "float3 EvoSunAt(float3 positionWS)",
        "float EvoBeamAt(float3 positionWS,",
        "float EvoPixelDither(float2 pixel)"))
    field += function(volume, "bool EvoClipToWater(float3 origin,")
    write("TheatreLightFieldHdrp.hlsl", "TheatreWater.hlsl and TheatreVolume.hlsl", field,
          "EVOSIM_THEATRE_LIGHT_FIELD_HDRP_INCLUDED")

    # The shaft march's own helpers. They read the march material's properties, which the
    # including shader declares first.
    march = open(os.path.join(SRC, "TheatreShaftMarch.shader"), encoding="utf-8").read()
    shaft = "".join(function(march, s) for s in (
        "float CapShade(float3 p)",
        "float2 SurfaceEntry(float3 p)",
        "float PlaceMask(float2 top,",
        "float SheetAt(float2 top,"))
    write("TheatreShaftHdrp.hlsl", "TheatreShaftMarch.shader",
          '#include "TheatreNoiseHdrp.hlsl"\n#include "TheatreLightFieldHdrp.hlsl"\n\n' + shaft,
          "EVOSIM_THEATRE_SHAFT_HDRP_INCLUDED")

    # The snow around the camera: the run's snow field, the two volume helpers the shells use, and
    # the shells' grid walk. The walk asks for the water path and the water's colour through
    # functions that read the camera or the engine's fog, so it calls the water pass's own, which
    # take the eye (origin, the shell's first argument) and the skin's deep colour.
    snow = open(os.path.join(SRC, "TheatreSnow.hlsl"), encoding="utf-8").read()
    shells = open(os.path.join(SRC, "TheatreSnowShells.shader"), encoding="utf-8").read()
    walk = function(shells, "float4 Shell(float3 origin,")
    for old, new in (("EvoWaterPathMetres(world)", "WaterPathMetres(origin, world)"),
                     ("EvoWaterColour(world.y)", "WaterColour(world.y)")):
        if walk.count(old) != 1:
            raise SystemExit(f"Shell: expected one {old}")
        walk = walk.replace(old, new)
    body = between(snow, "TEXTURE2D(_EvoSnowField);", "// How pale the bed is")
    body += function(volume, "bool EvoInWater(float3 p,")
    body += function(volume, "float EvoPixelMetres(float t)")
    body += walk
    write("TheatreSnowHdrp.hlsl", "TheatreSnow.hlsl, TheatreVolume.hlsl and TheatreSnowShells.shader",
          "// Included by TheatreWaterPass.shader after its WaterPathMetres and WaterColour, and after\n"
          "// the shells' material properties.\n\n" + body,
          "EVOSIM_THEATRE_SNOW_HDRP_INCLUDED")

    body = open(os.path.join(SRC, "TheatreBody.shader"), encoding="utf-8").read()
    # The shared HLSLINCLUDE block, from the vertex input to its ENDHLSL, and then the two pass
    # functions the surface needs, taken one by one so no pass header or URP include comes along.
    start = body.index("struct Attributes")
    start = body.rfind("\n\n", 0, start) + 2
    shape = body[start:body.index("\n        ENDHLSL", start) + 1] + "\n"
    shape += function(body, "void LeafVeins(float4 leaf,")
    shape += function(body, "float3 CarvedNormal(float3 normalWS,")
    # The URP pass's varyings are not used here; the graph carries its own interpolators.
    shape = re.sub(r"struct Varyings\s*\{.*?\};\n", "", shape, flags=re.S)
    # HDRP's own passes and libraries have structs of their own; a bare name could meet one.
    shape = re.sub(r"\bAttributes\b", "EvoBodyAttributes", shape)
    write("TheatreBodyShape.hlsl", "TheatreBody.shader", '#include "TheatreNoiseHdrp.hlsl"\n\n' + shape,
          "EVOSIM_THEATRE_BODY_SHAPE_INCLUDED")


if __name__ == "__main__":
    main()
