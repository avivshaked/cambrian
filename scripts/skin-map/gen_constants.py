"""Writes unity/Assets/Theatre/TheatreSkinMapConstants.cs from the skin map's two fixed-number files.

    python -I gen_constants.py [<projection.json> <weights.json> <out.cs> [<hybrid.json>]]

With no arguments it reads scratch/skin-map/pooled-24000/ in the main checkout and writes into the skin-map worktree. The
hybrid hue's constants (HybridFeatures, HybridWeights, HybridFittingScores, HybridRule) come from hue-screen/hybrid.json.
Every number is read from the files; none is typed here. A weight input marked "used": false is left out, which is
how skin_features.py drops a feature that was constant, failed the parent-and-child check or is not a feature of the run.
"""
import json
import sys

ROOT = 'D:/Projects/experiments/evolution-simulator'
PROJECTION = ROOT + '/scratch/skin-map/pooled-24000/projection.json'
WEIGHTS = ROOT + '/scratch/skin-map/pooled-24000/weights.json'
OUT = ROOT + '/scratch/wt-skin-map/unity/Assets/Theatre/TheatreSkinMapConstants.cs'
HYBRID = ROOT + '/scratch/skin-map/hue-screen/hybrid.json'


def lit(x):
    """A C# double literal that reads back to the same double."""
    r = repr(float(x))
    if r in ('inf', '-inf', 'nan'):
        raise ValueError('not finite: ' + r)
    return r


def main():
    projection, weights, out = (sys.argv[1:4] + [None, None, None])[:3]
    projection = projection or PROJECTION
    weights = weights or WEIGHTS
    out = out or OUT
    global HYBRID
    if len(sys.argv) > 4:
        HYBRID = sys.argv[4]

    p = json.load(open(projection, 'r', encoding='utf-8'))
    w = json.load(open(weights, 'r', encoding='utf-8'))

    names = p['features_all']
    index = {n: i for i, n in enumerate(names)}
    assert len(p['mean_all']) == len(names) == len(p['sd_all'])
    assert p['run'] == w['run'] and p['snapshot_seconds'] == w['snapshot_seconds'], 'projection and weights disagree'

    lines = []
    add = lines.append
    runs = [r for r in (p.get('reference_runs') or []) if not r.get('error')]
    pooled = bool(p.get('pooled')) and bool(runs)
    if pooled:
        reference = 'pooled non-producers of %d runs at their snapshot nearest %g s (%d bodies)' % (
            len(runs), runs[0]['asked_seconds'], p['n_reference'])
        short = ', '.join('%s %d' % (r['run'].rstrip('/').split('/')[-2] if '/' in r['run'] else r['run'],
                                     r['reference_bodies']) for r in runs)
    else:
        reference = 'run %s, bodies alive at the snapshot of %d s (%d bodies)' % (
            p['run'], p['snapshot_seconds'], p['n_reference'])
        short = ''
    add('// <auto-generated>')
    add('// Written by scripts/skin-map/gen_constants.py from projection.json and weights.json of the genome-to-skin')
    add('// map\'s first step: %s.' % reference)
    if pooled:
        add('// The reference is the bodies whose photosynthetic share of volume is under 0.5, pooled over the runs (bodies each):')
        add('// %s.' % short)
        add('// The weights and biases are folded: each parameter\'s gain and bias put the reference median body at 0.5.')
    add('// Redoing the projection is a ruled change (logbook/specs/theatre-skin-plan.md, section 5(c)): regenerate, do not edit.')
    add('// </auto-generated>')
    add('namespace Evosim.Theatre')
    add('{')
    add('    /// <summary>')
    add('    /// The fixed numbers of the genome-to-skin map (<see cref="TheatreSkinMap"/>): the reference population\'s mean and spread')
    add('    /// of each feature, the connection-count shrink of the brain markers, and each parameter\'s bias and weighted inputs (gain folded in).')
    add('    /// Reference: %s.' % reference)
    add('    /// </summary>')
    add('    internal static class TheatreSkinMapConstants')
    add('    {')
    add('        /// <summary>The reference run and the second of its snapshot, for the log.</summary>')
    add('        public const string Reference = "%s";' % reference)
    add('')
    add('        /// <summary>Each z is clipped to plus or minus this before the weighted sum.</summary>')
    add('        public const double ZClip = %s;' % lit(w['zclip']))
    add('')
    add('        /// <summary>Each brain_w_* z is multiplied by n / (n + this), n the connection count.</summary>')
    add('        public const double BrainShrinkLinks = %s;' % lit(p['brain_shrink_links']))
    add('')
    add('        /// <summary>The features, in the order of <see cref="Mean"/> and <see cref="Sd"/>.</summary>')
    add('        public static readonly string[] Features =')
    add('        {')
    for n in names:
        add('            "%s",' % n)
    add('        };')
    add('')
    add('        /// <summary>The reference population\'s mean of each feature. A spread of zero gives a z of zero.</summary>')
    add('        public static readonly double[] Mean =')
    add('        {')
    for n, v in zip(names, p['mean_all']):
        add('            %s, // %s' % (lit(v), n))
    add('        };')
    add('')
    add('        /// <summary>The reference population\'s standard deviation of each feature (population form).</summary>')
    add('        public static readonly double[] Sd =')
    add('        {')
    for n, v in zip(names, p['sd_all']):
        add('            %s, // %s' % (lit(v), n))
    add('        };')
    add('')
    add('        /// <summary>The ten parameters, in the order of the skin vector.</summary>')
    add('        public static readonly string[] ParameterNames =')
    add('        {')
    for q in w['parameters']:
        add('            "%s",' % q['name'])
    add('        };')
    add('')
    add('        /// <summary>Each parameter\'s bias.</summary>')
    add('        public static readonly double[] Bias =')
    add('        {')
    for q in w['parameters']:
        add('            %s, // %s' % (lit(q['bias']), q['name']))
    add('        };')
    add('')
    add('        /// <summary>')
    add('        /// Each parameter\'s inputs that are used: the feature\'s index in <see cref="Features"/> and its weight. A parameter with')
    add('        /// none is 0.5.')
    add('        /// </summary>')
    add('        public static readonly (int Feature, double Weight)[][] Inputs =')
    add('        {')
    for q in w['parameters']:
        used = [i for i in q['inputs'] if i['used']]
        if not used:
            add('            new (int, double)[0], // %s: no input is used, so it stays at 0.5' % q['name'])
            continue
        add('            new (int, double)[] // %s' % q['name'])
        add('            {')
        for i in used:
            assert i['feature'] in index, 'weight input %s is not a feature of the reference run' % i['feature']
            add('                (%d, %s), // %s' % (index[i['feature']], lit(i['weight']), i['feature']))
        add('            },')
    add('        };')

    hy = json.load(open(HYBRID, 'r', encoding='utf-8'))
    assert len(hy['features']) == len(hy['weights']), 'hybrid features and weights differ in length'
    for n in hy['features']:
        if n not in index:
            raise ValueError('hybrid feature %s is not a feature of the reference run' % n)
    scores = hy['fitting_scores_sorted']
    assert all(a <= b for a, b in zip(scores, scores[1:])), 'hybrid fitting scores are not sorted'
    add('')
    add('        /// <summary>The rule the hybrid constants below were written from (<c>EVOSIM_THEATRE_SKIN_MAP=2</c>).</summary>')
    add('        public const string HybridRule = "%s";' % hy['rule'])
    add('')
    add('        /// <summary>The features the hybrid hue\'s lineage score weighs, in the order of <see cref="HybridWeights"/>; each is one of <see cref="Features"/>.</summary>')
    add('        public static readonly string[] HybridFeatures =')
    add('        {')
    for n in hy['features']:
        add('            "%s",' % n)
    add('        };')
    add('')
    add('        /// <summary>The lineage score\'s weight on each of <see cref="HybridFeatures"/>\' clipped, shrunk z.</summary>')
    add('        public static readonly double[] HybridWeights =')
    add('        {')
    for n, v in zip(hy['features'], hy['weights']):
        add('            %s, // %s' % (lit(v), n))
    add('        };')
    add('')
    add('        /// <summary>The lineage scores of the fitting set (%d bodies), sorted ascending; a body\'s base hue is its middle rank among them.</summary>' % len(scores))
    add('        public static readonly double[] HybridFittingScores =')
    add('        {')
    for v in scores:
        add('            %s,' % lit(v))
    add('        };')
    add('    }')
    add('}')

    text = '\r\n'.join(lines) + '\r\n'
    with open(out, 'wb') as f:
        f.write(text.encode('utf-8'))
    print('wrote', out, len(lines), 'lines')


if __name__ == '__main__':
    main()
